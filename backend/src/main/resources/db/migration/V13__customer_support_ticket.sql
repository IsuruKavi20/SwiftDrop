-- Private cancellation reason for the customer detail page (never part of public tracking).
ALTER TABLE delivery ADD COLUMN cancellation_reason VARCHAR(200);

-- Dedicated customer support cases. Only customer-scoped APIs may access them.
-- Runs after the team customer identity migrations (V10-V12).
CREATE TABLE customer_support_ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer (customer_id),
    delivery_id BIGINT REFERENCES delivery (delivery_id),
    category VARCHAR(30) NOT NULL CHECK (category IN
        ('DELIVERY_STATUS', 'DELAY', 'DAMAGED_PARCEL', 'BILLING', 'OTHER')),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    subject VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_support_ticket_customer ON customer_support_ticket (customer_id, created_at);
CREATE INDEX idx_support_ticket_delivery ON customer_support_ticket (delivery_id);

CREATE TABLE customer_support_message (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES customer_support_ticket (ticket_id) ON DELETE CASCADE,
    sender_role VARCHAR(15) NOT NULL CHECK (sender_role IN ('CUSTOMER', 'STAFF')),
    message_text VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_support_message_ticket ON customer_support_message (ticket_id, created_at);
