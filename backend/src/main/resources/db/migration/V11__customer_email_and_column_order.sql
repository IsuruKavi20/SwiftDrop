-- Customer table rebuilt so its columns read in a natural order:
--   customer_id, auth_user_id, full_name, email, phone_number, created_at, updated_at
-- PostgreSQL cannot move columns, so the table is copied into a new one (same ids, same rows) and swapped in.
-- email: the customer's login email, copied from their access token when they register (backend fills old rows).

-- 1. The new table, columns in order
CREATE TABLE customer_new (
    customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,  -- primary key added after the swap (name taken)
    auth_user_id  UUID         NOT NULL,
    full_name     VARCHAR(150),
    email         VARCHAR(150),
    phone_number  VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Same rows, same ids (deliveries and addresses keep pointing at the right customer).
--    The old email column was never filled, so emails start empty and the backend fills them in.
INSERT INTO customer_new (customer_id, auth_user_id, full_name, phone_number, created_at, updated_at)
SELECT customer_id, auth_user_id, full_name, phone_number, created_at, updated_at
FROM customer;

-- 3. Swap. CASCADE removes only the foreign keys pointing at the old table (customer_address, delivery), never
--    their rows; they are added back below, pointing at the new one. Nothing else depends on this table.
DROP TABLE customer CASCADE;
ALTER TABLE customer_new RENAME TO customer;

ALTER TABLE customer ADD CONSTRAINT customer_pkey PRIMARY KEY (customer_id);
ALTER TABLE customer ADD CONSTRAINT customer_auth_user_id_key UNIQUE (auth_user_id);
ALTER TABLE customer ADD CONSTRAINT fk_customer_user FOREIGN KEY (auth_user_id) REFERENCES app_users (id);
ALTER TABLE customer_address ADD CONSTRAINT customer_address_customer_id_fkey
    FOREIGN KEY (customer_id) REFERENCES customer (customer_id) ON DELETE CASCADE;
ALTER TABLE delivery ADD CONSTRAINT delivery_customer_id_fkey
    FOREIGN KEY (customer_id) REFERENCES customer (customer_id);

