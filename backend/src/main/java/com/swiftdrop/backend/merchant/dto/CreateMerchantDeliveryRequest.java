package com.swiftdrop.backend.merchant.dto;

import com.swiftdrop.backend.customer.dto.DeliveryAddressRequest;
import com.swiftdrop.backend.customer.dto.ParcelRequest;
import com.swiftdrop.backend.customer.entity.DeliveryType;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.List;

/**
 * A new delivery booking created by a merchant. The merchant is inferred from the caller's access token,
 * and the tracking number, public tracking token, status, and estimated delivery date are generated by the backend.
 */
public record CreateMerchantDeliveryRequest(
        @NotNull DeliveryType deliveryType,
        @NotNull @Valid DeliveryAddressRequest pickup,
        @NotNull @Valid DeliveryAddressRequest destination,
        @NotEmpty @Size(max = 20) List<@NotNull @Valid ParcelRequest> parcels,
        @Size(max = 500) String specialInstructions) {
}
