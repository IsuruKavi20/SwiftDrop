package com.swiftdrop.backend.customer.service;

import com.swiftdrop.backend.customer.dto.DeliveryDetailsResponse;
import com.swiftdrop.backend.customer.entity.DeliveryStatus;
import com.swiftdrop.backend.customer.exception.ConflictException;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.stereotype.Service;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.UUID;

/** Downloadable delivery receipt, generated on demand from the persisted owner-scoped delivery. */
@Service
public class CustomerReceiptService {
    private final CustomerDeliveryService deliveries;
    public CustomerReceiptService(CustomerDeliveryService deliveries) { this.deliveries = deliveries; }

    public byte[] pdf(UUID userId, Long deliveryId) {
        DeliveryDetailsResponse d = deliveries.getDeliveryDetails(userId, deliveryId);
        if (d.status() != DeliveryStatus.DELIVERED) throw new ConflictException("Receipt is available after successful delivery");
        try (PDDocument doc = new PDDocument(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            PDPage page = new PDPage(PDRectangle.A4);
            doc.addPage(page);
            PDType1Font regular = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
            PDType1Font bold = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            try (PDPageContentStream content = new PDPageContentStream(doc, page)) {
                content.setNonStrokingColor(63,47,31);
                write(content,bold,22,48,790,"SwiftDrop | Delivery Receipt");
                line(content,48,775,547);
                float y = 747;
                y=entry(content,bold,regular,y,"Receipt number", "SD-R-"+d.id());
                y=entry(content,bold,regular,y,"Tracking number", d.trackingNumber());
                y=entry(content,bold,regular,y,"Status", d.status().name());
                y=entry(content,bold,regular,y,"Delivered on", d.deliveredAt() == null ? "-" :
                    DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm").withZone(ZoneId.of("Asia/Colombo")).format(d.deliveredAt()));
                y-=14;
                y=entry(content,bold,regular,y,"Sender", d.pickup()==null?"-":d.pickup().contactName());
                y=entry(content,bold,regular,y,"Pickup", d.pickup()==null?"-":d.pickup().city()+", "+d.pickup().district());
                y=entry(content,bold,regular,y,"Recipient",d.destination()==null?"-":d.destination().contactName());
                y=entry(content,bold,regular,y,"Destination",d.destination()==null?"-":d.destination().city()+", "+d.destination().district());
                y=entry(content,bold,regular,y,"Parcels",String.valueOf(d.parcels().size()));
                y=entry(content,bold,regular,y,"Estimated fee", d.estimatedFee()==null ? "Not recorded" : "LKR "+d.estimatedFee());
                write(content,regular,9,48,88,"Generated by SwiftDrop. Delivery fee is an estimate, not proof of payment.");
            }
            doc.save(out);
            return out.toByteArray();
        } catch (IOException e) { throw new IllegalStateException("Could not create receipt",e); }
    }
    private static void line(PDPageContentStream c,float x,float y,float x2) throws IOException {
        c.setLineWidth(0.7f); c.moveTo(x,y);c.lineTo(x2,y);c.stroke();
    }
    private static float entry(PDPageContentStream c, PDType1Font b, PDType1Font r,float y,String key,String value) throws IOException {
        write(c,b,11,48,y,key);write(c,r,11,210,y,value);return y-27;
    }
    private static void write(PDPageContentStream c,PDType1Font f,int size,float x,float y,String text) throws IOException {
        // Standard PDF font supports Latin-1. Replace unsupported glyphs safely for demo receipts.
        String safe = text.replaceAll("[^\\p{ASCII}]","?");
        if(safe.length()>54) safe=safe.substring(0,51)+"...";
        c.beginText();c.setFont(f,size);c.newLineAtOffset(x,y);c.showText(safe);c.endText();
    }
}
